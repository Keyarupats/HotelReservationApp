CREATE TABLE tblGuests (
        GuestId INT IDENTITY(1,1) PRIMARY KEY NOT NULL,
        GuestCode AS ('G-' + RIGHT('0000' + CAST(GuestId AS VARCHAR(4)), 4)) PERSISTED NOT NULL,
        ContactNo NVARCHAR(20) UNIQUE NOT NULL,
        FirstName NVARCHAR(50) NOT NULL,
        LastName NVARCHAR(50) NOT NULL,
        MI NVARCHAR(5) NULL,
        Age INT NOT NULL CHECK (Age >= 18),
        Address NVARCHAR(255) NOT NULL,
        Email NVARCHAR(100) NOT NULL,
        IDType NVARCHAR(50) NOT NULL,
        IDNum NVARCHAR(50) NOT NULL,
        IsActive BIT NOT NULL DEFAULT 1,
        CreatedAt DATETIME NOT NULL DEFAULT GETDATE()
    );
GO